def set_run_font(run, name='Arial Unicode MS', size=10.5, bold=False, underline=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.underline = underline

def set_cell_shading(cell, fill='F2F2F2'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd'); shd.set(qn('w:fill'), fill); tcPr.append(shd)

def style_doc(doc):
    sec = doc.sections[0]
    sec.page_width = Inches(8.268)
    sec.page_height = Inches(11.693)
    sec.top_margin = Inches(1)
    sec.bottom_margin = Inches(1)
    sec.left_margin = Inches(1.25)
    sec.right_margin = Inches(1.25)
    normal = doc.styles['Normal']
    normal.font.name = 'Arial Unicode MS'; normal._element.rPr.rFonts.set(qn('w:eastAsia'), 'Arial Unicode MS'); normal.font.size = Pt(10.5)
    normal.paragraph_format.line_spacing = 1.25
    normal.paragraph_format.space_after = Pt(6)
    for nm, size, before, after in [('Heading 1',22,17,16.5),('Heading 2',16,13,13),('Heading 3',12,8,6)]:
        st=doc.styles[nm]; st.font.name='Arial Unicode MS'; st._element.rPr.rFonts.set(qn('w:eastAsia'),'Arial Unicode MS'); st.font.size=Pt(size); st.font.bold=True
        st.paragraph_format.space_before=Pt(before); st.paragraph_format.space_after=Pt(after); st.paragraph_format.keep_with_next=True

def para(doc, text='', style='Normal', bold=False, underline=False, align=None, size=None):
    p=doc.add_paragraph(style=style)
    if align: p.alignment=align
    r=p.add_run(text); set_run_font(r, 'Arial Unicode MS', size or (22 if style=='Heading 1' else 16 if style=='Heading 2' else 10.5), bold or style.startswith('Heading'), underline)
    return p

def note(doc, text):
    p=doc.add_paragraph(); p.paragraph_format.left_indent=Inches(.18); p.paragraph_format.right_indent=Inches(.18)
    r=p.add_run('提示：'+text); set_run_font(r, 'Arial Unicode MS', 10, False)
    return p

def blank(doc, label, n=24):
    return para(doc, f'{label}：'+('_'*n))

