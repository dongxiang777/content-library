def cover(doc, title, subtitle):
    para(doc, title, 'Heading 1', align=WD_ALIGN_PARAGRAPH.CENTER)
    para(doc, subtitle, align=WD_ALIGN_PARAGRAPH.CENTER, size=12)
    para(doc, '')
