def table(doc, headers, rows, widths=None, header_fill=LIGHT, font_size=9.2):
    widths = widths or [CONTENT_W // len(headers)] * len(headers)
    if sum(widths) != CONTENT_W:
        widths[-1] += CONTENT_W - sum(widths)
    t = doc.add_table(rows=1, cols=len(headers))
    set_table_geometry(t, widths)
    repeat_header(t.rows[0])
    for index, header in enumerate(headers):
        cell = t.rows[0].cells[index]
        shade(cell, header_fill)
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(str(header))
        set_font(r, FONT, font_size, True)
    cant_split(t.rows[0])

    for row_values in rows:
        cells = t.add_row().cells
        for index, value in enumerate(row_values):
            cell = cells[index]
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if index == 0 else WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_after = Pt(0)
            for line_index, line in enumerate(str(value).split("\n")):
                if line_index:
                    p.add_run().add_break()
                run = p.add_run(line)
                set_font(run, FONT, font_size)
        if len(str(row_values[0])) < 40:
            cant_split(t.rows[-1])
    add_p(doc, "", after=2)
    return t


