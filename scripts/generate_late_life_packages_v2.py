    sec.top_margin=Inches(1); sec.bottom_margin=Inches(1); sec.left_margin=Inches(1.25); sec.right_margin=Inches(1.25)
    sec.header_distance=Inches(.5); sec.footer_distance=Inches(.5)
    normal=doc.styles['Normal']; normal.font.name=FONT; normal._element.rPr.rFonts.set(qn('w:eastAsia'),FONT); normal.font.size=Pt(10.5)
    normal.paragraph_format.line_spacing=1.25; normal.paragraph_format.space_after=Pt(6)
