def table(doc, headers, rows, widths=None, header_fill=LIGHT):
    t=doc.add_table(rows=1, cols=len(headers));
    widths=widths or [int(9360/len(headers))]*len(headers)
    set_table_geometry(t,widths)
    for i,h in enumerate(headers):
        c=t.rows[0].cells[i]; shade(c,header_fill); c.text=''
        p=c.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.CENTER; r=p.add_run(h); set_font(r,FONT,10,True)
    for row in rows:
        cells=t.add_row().cells
        for i,val in enumerate(row):
            cells[i].text=''; p=cells[i].paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.LEFT if i else WD_ALIGN_PARAGRAPH.CENTER
            r=p.add_run(str(val)); set_font(r,FONT,9.5)
    add_p(doc,'')
    return t

